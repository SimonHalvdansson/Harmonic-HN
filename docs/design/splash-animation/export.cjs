/* node docs/design/splash-animation/export.cjs */
const fs=require('node:fs'),path=require('node:path'),motion=require('./motion.js');
const geometry=JSON.parse(fs.readFileSync(path.join(__dirname,'icon-geometry.json'),'utf8'));
const original=fs.readFileSync(path.resolve(__dirname,'../../..',geometry.source));
const d=motion.finalPaths.join(' ');
const out=path.join(__dirname,'export');fs.mkdirSync(out,{recursive:true});
const installAndroid=process.argv.includes('--android');
fs.writeFileSync(path.join(__dirname,'preview-data.js'),`window.HarmonicIcon=${JSON.stringify(geometry)};\nwindow.HarmonicSource="data:image/png;base64,${original.toString('base64')}";\n`);
fs.writeFileSync(path.join(out,'harmonic-foreground.svg'),`<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024"><title>Harmonic foreground, smooth curves based on the production PNG</title><path fill="none" stroke="${geometry.ink}" stroke-width="${motion.strokeWidth}" stroke-linecap="round" stroke-linejoin="round" d="${d}"/></svg>\n`);
const background='M512,170.667 A341.333,341.333 0,1 1,512,853.333 A341.333,341.333 0,1 1,512,170.667 Z';
const n=v=>typeof v==='number'?v.toFixed(5):v;
function target(name,property,values,type='floatType') {
  // Path-valued XML keyframes aren't supported by Android's inflater.
  // Consecutive valueFrom/valueTo animators match the browser's linear samples.
  if(values.every(v=>v===values[0]))return '';
  return `  <target android:name="${name}"><aapt:attr name="android:animation"><set android:ordering="sequentially">\n`+
    values.slice(1).map((v,i)=>`    <objectAnimator android:propertyName="${property}" android:valueType="${type}" android:duration="${motion.interval}" android:interpolator="@android:interpolator/linear" android:valueFrom="${n(values[i])}" android:valueTo="${n(v)}"/>`).join('\n')+
    '\n  </set></aapt:attr></target>\n';
}
for(const variant of motion.variants) {
  const frames=motion.frames(geometry,variant.id),start=frames[0];
  const layers=start.layers.map((l,i)=>`      <group android:name="ribbon_group_${i}" android:pivotX="512" android:pivotY="512" android:rotation="${l.rotation}" android:translateX="${l.tx}" android:translateY="${l.ty}">\n        <path android:name="ribbon_${i}" android:fillColor="#00000000" android:strokeColor="${geometry.ink}" android:strokeWidth="${motion.strokeWidth}" android:strokeLineCap="round" android:strokeLineJoin="round" android:strokeAlpha="${l.alpha}" android:pathData="${motion.strokePath(l.points)}"/>\n      </group>`).join('\n');
  let animation='';
  for(let i=0;i<2;i++) {
    animation+=target(`ribbon_${i}`,'pathData',frames.map(f=>motion.strokePath(f.layers[i].points)),'pathType');
    animation+=target(`ribbon_${i}`,'strokeAlpha',frames.map(f=>f.layers[i].alpha));
    for(const [key,property] of [['rotation','rotation'],['tx','translateX'],['ty','translateY']])animation+=target(`ribbon_group_${i}`,property,frames.map(f=>f.layers[i][key]));
  }
  const xml=`<?xml version="1.0" encoding="utf-8"?>\n<animated-vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt">\n  <aapt:attr name="android:drawable">\n    <vector android:width="288dp" android:height="288dp" android:viewportWidth="1024" android:viewportHeight="1024">\n      <path android:fillColor="${geometry.background}" android:pathData="${background}"/>\n${layers}\n    </vector>\n  </aapt:attr>\n${animation}</animated-vector>\n`;
  fs.writeFileSync(path.join(out,`ic_harmonic_splash_${variant.id}.xml`),xml);
  if(variant.id==='gather') {
    fs.writeFileSync(path.join(out,'ic_harmonic_splash.xml'),xml);
    if(installAndroid) {
      const res=path.resolve(__dirname,'../../../app/src/main/res');
      fs.mkdirSync(path.join(res,'drawable-v31'),{recursive:true});
      fs.writeFileSync(path.join(res,'drawable-v31/ic_harmonic_splash_gather.xml'),
        xml.replace('<animated-vector', '<!-- Generated by docs/design/splash-animation/export.cjs with the Android sync flag. Edit motion.js, then regenerate. -->\n<animated-vector'));
      fs.writeFileSync(path.join(res,'values-v31/splash_animation.xml'),
        `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by docs/design/splash-animation/export.cjs with the Android sync flag. -->\n<resources>\n    <!-- Animation metadata only; does not extend the splash lifetime. -->\n    <integer name="splash_icon_animation_duration">${motion.duration}</integer>\n</resources>\n`);
      console.log('Installed Gather and its duration in Android API 31 resources.');
    }
  }
  console.log(`${variant.name}: ${motion.duration} ms; exported browser-equivalent AVD.`);
}



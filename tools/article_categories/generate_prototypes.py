"""Fit centered title/preview references and export their paired app resources."""
import argparse
import json
import struct
from pathlib import Path
from category_model import MODEL_SHA256, corpus_fingerprint, fit, has_preview, labels, policy, representation, scores, summarize

MODEL_REVISION = "9be6e8b90982095dc05c2bd162e4b954ee4dbac7"
def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument("embeddings", type=Path)
    parser.add_argument("--corpus", type=Path, default=Path(__file__).with_name("corpus.json"))
    parser.add_argument("--kotlin", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True, help="Keep evaluation output outside the repository")
    parser.add_argument("--training-data", type=Path, help="Export editable default examples and both vector views as an HNC2 resource")
    parser.add_argument("--cutoff", type=float, default=policy()['cutoff'])
    args = parser.parse_args()
    corpus = json.loads(args.corpus.read_text(encoding="utf-8"))
    vectors = {item["hn_id"]: item for item in json.loads(args.embeddings.read_text(encoding="utf-8"))}
    origin, centers, training_vectors = fit(corpus,vectors)
    title_origin, title_centers, title_vectors = fit(corpus,vectors,title_only=True)
    rows = []
    for example in corpus["examples"]:
        if example["split"] == "train":
            continue
        row = {"hn_id": example["hn_id"], "title": example["title"], "expected": example["category_ids"],
               "acceptable": example.get('acceptable_category_ids',example['category_ids']), 'evaluation_set':example.get('evaluation_set','curated')}
        record=vectors[example['hn_id']]
        for field in ('preview','title_only'):
            title_only = field == 'title_only' or not has_preview(record)
            vector = representation(record,title_only)
            values=scores(vector,title_origin if title_only else origin,title_centers if title_only else centers)
            row[field]={'scores':{key:round(value,6) for key,value in values.items()},'predicted':labels(values,args.cutoff)}
        rows.append(row)
    report={'policy':policy(),'corpus_sha256':corpus_fingerprint(corpus),
            'summary':{field:summarize(rows,field) for field in ('preview','title_only')},'holdouts':rows}
    args.report.write_text(json.dumps(report,indent=2),encoding='utf-8',newline='\n')
    lines = ["// Generated by tools/article_categories/generate_prototypes.py. Do not edit vectors by hand.",
             f"// Model revision: {MODEL_REVISION}; SHA-256: {MODEL_SHA256}",
             f"// Corpus SHA-256: {corpus_fingerprint(corpus)}",
             "package com.simon.harmonichackernews.categorization", "",
             f"// Input: {policy()['input_version']}; representation: {policy()['representation_version']}",
             "internal object ArticleCategoryPrototypes {", "    val origin: FloatArray by lazy { background() }",
             "    val titleOrigin: FloatArray by lazy { headlineBackground() }",
             "    val vectors: Map<String, FloatArray> by lazy { mapOf("]
    for key in centers:
        lines.append(f'        "{key}" to {key}(),')
    lines.extend(["    ) }", "", "    val titleVectors: Map<String, FloatArray> by lazy { mapOf("])
    for key in title_centers:
        lines.append(f'        "{key}" to title_{key}(),')
    lines.extend(["    ) }", ""])
    for key, vector in {'background':origin,'headlineBackground':title_origin,**centers,**{'title_'+key:value for key,value in title_centers.items()}}.items():
        lines.append(f"    private fun {key}() = floatArrayOf(")
        for start in range(0, len(vector), 8):
            lines.append("        " + ", ".join(f"{value:.9f}f" for value in vector[start:start + 8]) + ",")
        lines.extend(["    )", ""])
    lines.append("}")
    args.kotlin.write_text("\n".join(lines) + "\n", encoding="utf-8",newline='\n')
    if args.training_data:
        training = [x for x in corpus["examples"] if x["split"] == "train"]
        header = {
            "modelSha256": MODEL_SHA256,
            "inputVersion": policy()['input_version'],
            "representationVersion": policy()['representation_version'],
            "stories": [{"id": x["hn_id"], "title": x["title"], "url": x["url"], "description": x["description"], "source": "default"} for x in training],
            "assignments": {c["id"]: [x["hn_id"] for x in training if c["id"] in x["category_ids"]] for c in corpus["categories"]},
        }
        metadata = json.dumps(header, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
        args.training_data.parent.mkdir(parents=True, exist_ok=True)
        with args.training_data.open("wb") as output:
            output.write(b"HNC2" + struct.pack("<I", len(metadata)) + metadata)
            for example in training:
                output.write(struct.pack("<768f", *training_vectors[example['hn_id']]))
                output.write(struct.pack("<768f", *title_vectors[example['hn_id']]))
    print(f"Exported {len(centers)} normalized 768-dimensional centers; evaluated {len(rows)} holdouts")


if __name__ == "__main__":
    main()

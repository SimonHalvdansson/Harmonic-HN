"""Average normalized training vectors; evaluate untouched holdouts and export Kotlin centers."""
import argparse
import hashlib
import json
import math
import struct
from pathlib import Path

MODEL_REVISION = "9be6e8b90982095dc05c2bd162e4b954ee4dbac7"
MODEL_SHA256 = "2d079ee2f6f066b1f368e8d7c819f55214eaef1d0513b312321901f30ab286fb"


def normalize(vector):
    if len(vector) != 768 or not all(math.isfinite(x) for x in vector):
        raise ValueError("Expected 768 finite dimensions")
    length = math.sqrt(sum(x * x for x in vector))
    if not length:
        raise ValueError("Zero embedding")
    return [x / length for x in vector]


def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument("embeddings", type=Path)
    parser.add_argument("--corpus", type=Path, default=Path(__file__).with_name("corpus.json"))
    parser.add_argument("--kotlin", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True, help="Keep evaluation output outside the repository")
    parser.add_argument("--training-data", type=Path, help="Export editable default examples and vectors as an HNC1 resource")
    parser.add_argument("--cutoff", type=float, default=0.78)
    args = parser.parse_args()
    corpus = json.loads(args.corpus.read_text(encoding="utf-8"))
    vectors = {item["hn_id"]: item for item in json.loads(args.embeddings.read_text(encoding="utf-8"))}
    centers = {}
    for category in corpus["categories"]:
        training = [normalize(vectors[x["hn_id"]]["embedding"]) for x in corpus["examples"]
                    if x["split"] == "train" and category["id"] in x["category_ids"]]
        if len(training) < 2:
            raise ValueError("Each category needs at least two training examples")
        centers[category["id"]] = normalize([sum(values) / len(training) for values in zip(*training)])
    rows = []
    for example in corpus["examples"]:
        if example["split"] == "train":
            continue
        row = {"hn_id": example["hn_id"], "title": example["title"], "expected": example["category_ids"]}
        for field in ("embedding", "title_embedding"):
            vector = normalize(vectors[example["hn_id"]][field])
            scores = {key: round(sum(x * y for x, y in zip(vector, center)), 6) for key, center in centers.items()}
            row[field] = {"scores": scores, "predicted": [key for key, score in sorted(scores.items(), key=lambda x: -x[1]) if score >= args.cutoff][:3]}
        rows.append(row)
    args.report.write_text(json.dumps({"cutoff": args.cutoff, "holdouts": rows}, indent=2), encoding="utf-8")
    lines = ["// Generated by tools/article_categories/generate_prototypes.py. Do not edit vectors by hand.",
             f"// Model revision: {MODEL_REVISION}; SHA-256: {MODEL_SHA256}",
             f"// Corpus SHA-256: {hashlib.sha256(args.corpus.read_bytes()).hexdigest()}",
             "package com.simon.harmonichackernews.categorization", "",
             "internal object ArticleCategoryPrototypes {", "    val vectors: Map<String, FloatArray> by lazy { mapOf("]
    for key in centers:
        lines.append(f'        "{key}" to {key}(),')
    lines.extend(["    ) }", ""])
    for key, vector in centers.items():
        lines.append(f"    private fun {key}() = floatArrayOf(")
        for start in range(0, len(vector), 8):
            lines.append("        " + ", ".join(f"{value:.9f}f" for value in vector[start:start + 8]) + ",")
        lines.extend(["    )", ""])
    lines.append("}")
    args.kotlin.write_text("\n".join(lines) + "\n", encoding="utf-8")
    if args.training_data:
        training = [x for x in corpus["examples"] if x["split"] == "train"]
        header = {
            "modelSha256": MODEL_SHA256,
            "stories": [{"id": x["hn_id"], "title": x["title"], "url": x["url"], "description": x["description"], "source": "default"} for x in training],
            "assignments": {c["id"]: [x["hn_id"] for x in training if c["id"] in x["category_ids"]] for c in corpus["categories"]},
        }
        metadata = json.dumps(header, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
        args.training_data.parent.mkdir(parents=True, exist_ok=True)
        with args.training_data.open("wb") as output:
            output.write(b"HNC1" + struct.pack("<I", len(metadata)) + metadata)
            for example in training:
                output.write(struct.pack("<768f", *normalize(vectors[example["hn_id"]]["embedding"])))
    print(f"Exported {len(centers)} normalized 768-dimensional centers; evaluated {len(rows)} holdouts")


if __name__ == "__main__":
    main()

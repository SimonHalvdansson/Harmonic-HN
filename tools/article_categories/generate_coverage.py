"""Bake the sampled popular stories' best similarities into the cutoff curve."""
import argparse
import json
from pathlib import Path
from category_model import (MODEL_SHA256, corpus_fingerprint, fit, has_preview, labels,
                            policy, representation, scores, validate_records)
from merge_corpus import article_key


def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument('embeddings', type=Path)
    parser.add_argument('--reference-embeddings', type=Path, required=True)
    parser.add_argument('--sample', type=Path, default=Path(__file__).with_name('corpus_coverage.json'))
    parser.add_argument('--corpus', type=Path, default=Path(__file__).with_name('corpus.json'))
    parser.add_argument('--kotlin', type=Path, required=True)
    parser.add_argument('--report', type=Path, required=True, help='Keep score diagnostics outside the repository')
    args = parser.parse_args()
    sample = json.loads(args.sample.read_text(encoding='utf-8'))
    corpus = json.loads(args.corpus.read_text(encoding='utf-8'))
    records = {x['hn_id']: x for x in json.loads(args.embeddings.read_text(encoding='utf-8'))}
    references = {x['hn_id']: x for x in json.loads(args.reference_embeddings.read_text(encoding='utf-8'))}
    assert len(sample['examples']) == len({x['hn_id'] for x in sample['examples']}) == 100
    assert len({article_key(x['url']) for x in sample['examples']}) == 100
    assert sample['description_pipeline'] == 'HtmlDescriptionExtractor.previewDescription; 600 characters; v1'
    training_urls = {article_key(x['url']) for x in corpus['examples'] if x['split'] == 'train'}
    assert all(x['score'] >= 100 and x['split'] == 'coverage' and not x['category_ids'] and
               article_key(x['url']) not in training_urls for x in sample['examples'])
    validate_records(sample, records)
    preview = fit(corpus, references)
    headline = fit(corpus, references, title_only=True)
    rows = []
    for story in sample['examples']:
        record = records[story['hn_id']]
        title_only = not has_preview(record)
        origin, centers, _ = headline if title_only else preview
        values = scores(representation(record, title_only), origin, centers)
        rows.append(dict(hn_id=story['hn_id'], title=story['title'], has_preview=not title_only,
                         best_score=max(values.values()), scores=values, labels=labels(values)))
    report = dict(collected_at=sample['collected_at'], model_sha256=MODEL_SHA256, policy=policy(),
                  reference_sha256=corpus_fingerprint(corpus), sample_sha256=corpus_fingerprint(sample), stories=rows)
    args.report.write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n', encoding='utf-8', newline='\n')
    lines = ['// Generated by tools/article_categories/generate_coverage.py. Do not edit scores by hand.',
             f"// 100 randomly sampled popular HN stories; collected {sample['collected_at']}; seed {sample['seed']}.",
             f'// Model SHA-256: {MODEL_SHA256}',
             f"// Input: {policy()['input_version']}; representation: {policy()['representation_version']}",
             f'// Reference corpus SHA-256: {corpus_fingerprint(corpus)}',
             f'// Coverage sample SHA-256: {corpus_fingerprint(sample)}',
             'package com.simon.harmonichackernews.ui.settings', '',
             '/** A fixed score distribution from popular stories, independent of browsing history. */',
             'internal object CategoryCoverageReference {', '    val bestScores: List<Float> = listOf(']
    values = sorted(x['best_score'] for x in rows)
    for offset in range(0, len(values), 8):
        lines.append('        ' + ', '.join(f'{x:.9f}f' for x in values[offset:offset + 8]) + ',')
    lines.extend(['    )', '    val curve: List<CategoryCoveragePoint> by lazy { CategoryCoverage(bestScores).curve() }', '}', ''])
    args.kotlin.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    for cutoff in (0.10, 0.20, 0.24, 0.30, 0.40, 0.45):
        print(f'Cutoff {cutoff:.2f}: {sum(x >= cutoff for x in values)}/100 stories labeled')
    print(f"Useful previews: {sum(x['has_preview'] for x in rows)}/100")


if __name__ == '__main__':
    main()
